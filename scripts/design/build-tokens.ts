/**
 * design/lab-ui/tokens.source.json → src/web/ui/tokens/tokens.css
 * Производные токены собираются как «цвет × непрозрачность» (архитектура Lab UI v2.1.1):
 * бренд-цвет меняется в одном месте — `--lab-color-blue`.
 *
 * Запуск: node scripts/design/build-tokens.ts
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const source = JSON.parse(readFileSync(path.join(ROOT, 'design/lab-ui/tokens.source.json'), 'utf8')) as {
  primitive: Record<'color' | 'alpha' | 'radius' | 'space' | 'blur' | 'duration' | 'ease', Record<string, string | number>>;
  type: { family: Record<string, string>; weight: Record<string, number>; scale: Record<string, { size: string; line: string; tracking: string }> };
  semantic: {
    light: Record<string, string | [string, number]>;
    dark: Record<string, string | [string, number]>;
    status: Record<string, string>;
    statusSteps: Record<string, number>;
  };
  shadow: { light: Record<string, string>; dark: Record<string, string> };
};

type Ref = string | [string, number];

function value(ref: Ref): string {
  if (typeof ref === 'string') return `var(--lab-color-${ref})`;
  const [color, alpha] = ref;
  return `color-mix(in srgb, var(--lab-color-${color}) calc(var(--lab-alpha-${alpha}) * 1%), transparent)`;
}

const lines: string[] = [];
const block = (selector: string, decls: string[]) => lines.push(`${selector} {`, ...decls.map((d) => `  ${d}`), '}', '');

const primitives: string[] = [];
for (const [name, hex] of Object.entries(source.primitive.color)) primitives.push(`--lab-color-${name}: ${hex};`);
for (const [name, pct] of Object.entries(source.primitive.alpha)) primitives.push(`--lab-alpha-${name}: ${pct};`);
for (const group of ['radius', 'space', 'blur', 'duration', 'ease'] as const) {
  for (const [name, v] of Object.entries(source.primitive[group])) primitives.push(`--lab-${group}-${name}: ${v};`);
}
for (const [name, v] of Object.entries(source.type.family)) primitives.push(`--lab-font-${name}: ${v};`);
for (const [name, v] of Object.entries(source.type.weight)) primitives.push(`--lab-weight-${name}: ${v};`);
for (const [name, t] of Object.entries(source.type.scale)) {
  primitives.push(`--lab-type-${name}-size: ${t.size};`, `--lab-type-${name}-line: ${t.line};`, `--lab-type-${name}-tracking: ${t.tracking};`);
}
// Статусные цвета и их лестница: strong / muted / soft / softer / ring.
for (const [role, color] of Object.entries(source.semantic.status)) {
  for (const [step, alpha] of Object.entries(source.semantic.statusSteps)) {
    primitives.push(`--lab-${role}${step === 'strong' ? '' : `-${step}`}: ${alpha === 100 ? `var(--lab-color-${color})` : `color-mix(in srgb, var(--lab-color-${color}) ${alpha}%, transparent)`};`);
  }
}
primitives.push('--lab-scale: 1;');
block(':root', primitives);

function theme(name: 'light' | 'dark'): string[] {
  const decls = Object.entries(source.semantic[name]).map(([token, ref]) => `--lab-${token}: ${value(ref)};`);
  for (const [token, v] of Object.entries(source.shadow[name])) decls.push(`--lab-shadow-${token}: ${v};`);
  decls.push(`color-scheme: ${name};`);
  return decls;
}

block(':root, [data-theme="light"]', theme('light'));
block('[data-theme="dark"]', theme('dark'));
lines.push('@media (prefers-color-scheme: dark) {');
lines.push('  :root:not([data-theme]) {', ...theme('dark').map((d) => `    ${d}`), '  }', '}', '');
// Масштаб 75–133 %: все размеры в rem, меняется только корневой кегль.
block('html', ['font-size: calc(16px * var(--lab-scale));']);
for (const pct of [75, 90, 110, 125, 133]) block(`[data-scale="${pct}"]`, [`--lab-scale: ${pct / 100};`]);

const out = path.join(ROOT, 'src/web/ui/tokens/tokens.css');
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, `/* generated by scripts/design/build-tokens.ts — do not edit. Source: design/lab-ui/tokens.source.json */\n\n${lines.join('\n')}`);
console.log(`tokens.css: ${lines.filter((l) => l.trim().startsWith('--lab-')).length} деклараций`);
