/**
 * design/lab-ui/icons/*.svg (экспорт из Figma) → src/web/ui/icons/data.ts
 * Цвет заливки заменяется на currentColor: иконка наследует цвет текста. Лицензия Lab UI — CC BY 4.0.
 *
 * Запуск: node scripts/design/build-icons.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const wanted = JSON.parse(readFileSync(path.join(ROOT, 'design/lab-ui/icons-wanted.json'), 'utf8')) as Record<string, string>;

const icons: Record<string, { outline?: string; filled?: string }> = {};
for (const [key, id] of Object.entries(wanted)) {
  const [name = '', variant = ''] = key.split('.');
  const svg = readFileSync(path.join(ROOT, 'design/lab-ui/icons', `${id.replace(/[:;]/g, '-')}.svg`), 'utf8');
  const inner = (svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/)?.[1] ?? '')
    .replace(/\s(fill|stroke)="(?!none)[^"]*"/g, ' $1="currentColor"')
    .replace(/\s+/g, ' ')
    .trim();
  (icons[name] ??= {})[variant as 'outline' | 'filled'] = inner;
}

const names = Object.keys(icons).sort();
const body = names.map((name) => `  '${name}': ${JSON.stringify(icons[name])},`).join('\n');
writeFileSync(
  path.join(ROOT, 'src/web/ui/icons/data.ts'),
  `// generated by scripts/design/build-icons.ts — do not edit. Иконки Lab UI (lab.pics), CC BY 4.0.\n\nexport const ICONS = {\n${body}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`,
);
console.log(`иконок: ${names.length}`);
